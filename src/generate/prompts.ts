/**
 * 実物写真の挿入指示。サイトにアップ済みの写真だけを候補として渡す。
 * 体験レビューの説得力は実物写真でしか出せないため、文脈に合うものがあれば入れる。
 */
function photoInstruction(photos?: PhotoEntry[]): string {
  const list = photos ?? [];
  if (list.length === 0) return "";
  const lines = list
    .map((p) => `  - PHOTO_${p.id}: ${p.description}（使える話題: ${p.topics.join("・") || "-"}）`)
    .join("\n");
  return `- **実物写真を1〜3枚挿入する。** 下記から文脈に合うものを選び、本文の該当箇所に
  [PHOTO:<id>|<alt文>] の形で1行で書くこと（例: [PHOTO:471|洗濯表示タグの拡大]）。
  **リストに無いidを書いてはいけない。imgタグやURLを自分で書いてもいけない。**
  合う写真が無ければ1枚も入れなくてよい。無理に関係ない写真を入れない。
  altは画像に写っているものの客観的な説明にし、効果・効能を示唆しない。
${lines}`;
}

/** リライト（§5-1）用ユーザープロンプト。元記事を尊重し改善に徹する。 */
export function buildRewritePrompt(
  c: Candidate,
  originalTitle: string,
  originalHtml: string,
  ctxCatalog?: AffiliateShortcode[],
  photos?: PhotoEntry[],
): string {
  const m = c.metrics;
  const metrics = [
    m.position !== undefined ? `平均掲載順位 ${m.position.toFixed(1)}位` : null,
    m.ctr !== undefined ? `CTR ${(m.ctr * 100).toFixed(1)}%` : null,
    m.impressions !== undefined ? `インプレッション ${m.impressions}` : null,
    m.clicks !== undefined ? `クリック ${m.clicks}` : null,
  ].filter(Boolean).join(" / ");

  // 元記事にアフィリンクが無い場合は、サイト内で実在するショートコードから文脈に合うものを
  // 選んで挿入させる（IDの創作は禁止。カタログが無いときだけプレースホルダーに退避）。
  const hasAffiliate = /\[affi|amzn\.to|a\.r10\.to|amazon\.|rakuten\./i.test(originalHtml);
  const catalog = ctxCatalog ?? [];
  const catalogText = catalog
    .map((s) => `  - ${s.code}（サイト内${s.count}回使用 / 使用記事: ${s.articles.slice(0, 4).join(", ")}）\n      使用例の文脈: ${s.contexts[0] ?? "-"}`)
    .join("\n");
  const affiliateInstruction = hasAffiliate
    ? "- 本文中のアフィリエイトリンク（[affi id=x] 等）は**位置も含めて必ず維持**する。削除・改変しない。"
    : catalog.length
      ? `- **この記事にはアフィリエイトリンクが1本も無い。** 商品に言及している箇所や「選び方・まとめ・
  おすすめ」に相当する文脈を**1〜3箇所**選び、そこに下記リストから**文脈に最も合うショートコードを
  そのままの文字列で挿入**すること（例: 記事がBAKUNEの話ならBAKUNE系のコード）。
  **リストに無いIDを創作してはいけない。** 関連の薄い商品を無理に入れない（適切な箇所が無ければ入れない）。
  **各コードがどの商品を指すかは「使用記事」と「使用例の文脈」からのみ判断すること。**
  使用記事名・文脈から商品を特定できないコードは使わない。別商品のコードを、記事で扱っている
  商品のものだと推測して割り当ててはいけない（例: SIXPADのコードをBAKUNEの型番として使う等）。
${catalogText}`
      : "- この記事にはアフィリエイトリンクが無い。商品に言及する文脈が1〜2箇所あれば 【要確認: アフィリンク挿入】 を置くこと（URL・ショートコードの創作は禁止）。";

  return `既存記事を「リライト」して改善してください。改善タイプは ${c.rule} です。

## 改善の狙い（${c.rule}）
${c.rule === "R1" ? "検索上位に表示できているのにCTRが低い。タイトル・導入・見出し・メタ的要素を磨いてクリック率を上げる。本文の大幅な作り替えはしない。" : ""}${c.rule === "R3" ? "2ページ目付近。網羅性・見出し構成・要点提示を改善して1ページ目を狙う。元記事の主旨は維持。" : ""}${c.rule === "R2" ? "以前より順位が下落。情報の鮮度・網羅性・構成を見直して回復を狙う。元記事の主旨は維持。" : ""}${c.rule === "R4" ? "検索順位・流入は健全だが、読者が商品を検討する導線が弱く収益につながっていない。**順位を落とさないこと**を最優先に、記事の主旨・構成は維持したまま、読者が「どれを選べばいいか」判断できる箇所（選び方・比較・まとめ・FAQ）を自然に補強する。売り込み調にせず、あくまで読者の判断を助ける情報として整える。" : ""}

## 現状データ（GSC）
- 対象URL: ${c.targetUrl}
- ${metrics}
- 主な流入クエリ: ${c.queries.map((q) => `「${q}」`).join(" / ")}

## 元記事タイトル
${originalTitle}

## 元記事本文（HTML）
${originalHtml}

## 指示
- 元記事の構成・トーン・情報を尊重し、**全書き換えではなく改善**に徹する（見出しの意図や順序は極力維持）。
- 上記の流入クエリの検索意図に、より的確に応える（特にCTRを上げるための導入とタイトル）。
- 事実・数値・商品情報は元記事にあるもののみ使用。新しい事実主張・数値・比較を足さない。
${affiliateInstruction}
${photoInstruction(photos)}
- 表現ルール（薬機法・景表法）を厳守。
${c.rule === "R1" ? "- タイトル案を3つ提示する（クリックされやすく、かつ誇大にならない範囲で）。" : "- タイトル案を3つ提示する。"}

## 出力形式
下記の区切り行をそのまま使って出力してください。**JSONにしないこと。**
前後に説明文やコードフェンスを付けないこと。HTMLはエスケープせずそのまま書いてください。

===TITLES===
案1
案2
案3
===SUMMARY===
何をどう改善したかの箇条書き（プレーンテキスト、3〜6項目）
===HTML===
リライト後の本文HTML（<h2>等の見出し構造を含む。元記事の構成を尊重）
===END===`;
}

/** 新規記事（§5-2）用ユーザープロンプト。事実確認が必要な箇所はプレースホルダーにする。 */
export function buildNewArticlePrompt(
  c: Candidate,
  internalLinks: Array<{ title: string; url: string }>,
  ctxCatalog?: AffiliateShortcode[],
  photos?: PhotoEntry[],
): string {
  // URLを渡すので内部リンクは実リンクとして書かせる（プレースホルダーにしない）
  const links = internalLinks.slice(0, 30).map((l) => `- ${l.title} → ${l.url}`).join("\n");

  // 収益導線は既存記事のリライトと同じ型を使う。実在するショートコードから文脈で選ばせる。
  const catalog = ctxCatalog ?? [];
  const catalogText = catalog
    .map((s) => `  - ${s.code}（サイト内${s.count}回使用 / 使用記事: ${s.articles.slice(0, 4).join(", ")}）\n      使用例の文脈: ${s.contexts[0] ?? "-"}`)
    .join("\n");
  const affiliateInstruction = catalog.length
    ? `- 読者が商品を検討する文脈（選び方・比較・まとめ・FAQ）を**1〜3箇所**選び、下記リストから
  **文脈に最も合うショートコードをそのままの文字列で挿入**すること。
  **リストに無いIDを創作してはいけない。** 関連の薄い商品を無理に入れない。
  **各コードがどの商品を指すかは「使用記事」と「使用例の文脈」からのみ判断すること。**
  特定できないコードは使わない。別商品のコードを推測で割り当ててはいけない。
${catalogText}`
    : "- アフィリエイトリンクは 【要確認: アフィリンク挿入】 のプレースホルダーを置く（URL・ショートコードの創作は禁止）。";
  return `以下の検索需要に応える「新規記事」を書いてください（改善タイプ ${c.rule}）。

## 対象クエリ（検索需要）
${c.queries.map((q) => `「${q}」`).join(" / ")}
（想定インプレッション: ${c.metrics.impressions ?? "-"}）

## 指示
- 上記クエリの検索意図に正面から答える記事。結論先出し、見出し直下に要点、FAQ(Q&A)構造を活用。
- **商品の具体的スペック・比較データ・数値は創作しない。** 記事が事実として断定してしまい、
  かつ人間が調べて埋める必要がある箇所だけ 【要確認: ○○】 のプレースホルダーにする。
- **【要確認】を濫用しないこと。** 商品ごとに変わる仕様（ラインナップの有無、素材の混紡率、
  生地の厚み、サイズ展開など）は、価格と同じく「公式サイト（Amazon・楽天）でご確認ください」
  という読者への誘導文で書く。プレースホルダーにしない。
  悪い例:「【要確認: 各ブランドの裏起毛モデルの有無】は商品ごとに異なります」
  良い例:「裏起毛モデルがあるかどうかは商品ごとに異なるため、公式サイトでご確認ください」
  ※ カッコを外しても文章が成立するなら、それは【要確認】ではなく誘導文にすべき箇所。
- **価格は具体的な金額を書かない**（景表法の有利誤認回避）。「最新価格は公式サイト・Amazon・楽天でご確認ください」
  という誘導文にし、アフィリエイトリンクへの導線にする。【要確認】プレースホルダーにも金額は入れない。
- 表現ルール（薬機法・景表法）を厳守。断定的効能表現は禁止。
- 文字数目安 3000〜5000字。見出し(h2/h3)構造を付ける。
${affiliateInstruction}
${photoInstruction(photos)}
- 内部リンク候補（サイト内の既存記事とそのURL）。関連するものは本文中で自然に言及し、
  **<a href="URL">タイトル</a> の形で実際にリンクする**こと。無関係なものは入れない:
${links || "（なし）"}

## 出力形式
下記の区切り行をそのまま使って出力してください。**JSONにしないこと。**
前後に説明文やコードフェンスを付けないこと。HTMLはエスケープせずそのまま書いてください。

===TITLE===
記事タイトル案
===META===
メタディスクリプション案（120字程度）
===HTML===
本文HTML（<h2>等の見出し構造付き。事実未確認箇所は【要確認: ○○】）
===END===`;
}
